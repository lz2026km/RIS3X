async function handlePdfExport(opts: ExportOptions): Promise<ExportResult> {
  const html = buildHtmlReport(opts);
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const w = window.open(url);
  if (w) {
    w.addEventListener('afterprint', () => { w.close(); });
    w.print();
  }
  URL.revokeObjectURL(url);
  return { success: true, fileName: `${opts.reportId}.pdf` };
}

async function handleWordExport(opts: ExportOptions): Promise<ExportResult> {
  const html = buildWordHtml(opts);
  const blob = new Blob([html], { type: 'application/msword' });
  return { success: true, blob, fileName: `${opts.reportId}.doc` };
}

async function handleHtmlExport(opts: ExportOptions): Promise<ExportResult> {
  const html = buildHtmlReport(opts);
  const blob = new Blob([html], { type: 'text/html' });
  return { success: true, blob, fileName: `${opts.reportId}.html` };
}

async function handleTextExport(opts: ExportOptions): Promise<ExportResult> {
  const text = `放射诊断报告\n报告编号：${opts.reportId}\n检查日期：${new Date().toLocaleDateString('zh-CN')}\n\n影像所见\n—\n\n诊断意见\n—\n`;
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  return { success: true, blob, fileName: `${opts.reportId}.txt` };
}

async function handleHl7Export(opts: ExportOptions): Promise<ExportResult> {
  const hl7 = `MSH|^~\\&|RIS|HOSPITAL|||${new Date().toISOString()}||ORU^R01|${opts.reportId}|P|2.5.1\nPID|||12345||SMITH^JOHN||19700101|M\nOBR|1|${opts.reportId}||CT^ABDOMEN|||${new Date().toISOString()}\nOBX|1|TX||RADIOLOGY_REPORT|—|||F`;
  const blob = new Blob([hl7], { type: 'application/x-hl7' });
  return { success: true, blob, fileName: `${opts.reportId}.hl7` };
}

async function handleDicomSrExport(opts: ExportOptions): Promise<ExportResult> {
  const sr = {
    sopClassUID: '1.2.840.10008.5.1.4.1.1.88.22',
    studyInstanceUID: opts.reportId,
    patientName: '—',
    findings: '',
    conclusion: '',
    date: new Date().toISOString(),
  };
  const blob = new Blob([JSON.stringify(sr, null, 2)], { type: 'application/dicom+json' });
  return { success: true, blob, fileName: `${opts.reportId}.json` };
}

async function handleCsvExport(opts: ExportOptions): Promise<ExportResult> {
  const csv = '报告编号,姓名,性别,检查项目,检查日期,影像所见,诊断意见\n' +
    `${opts.reportId},—,—,—,${new Date().toLocaleDateString('zh-CN')},—,—\n`;
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8' });
  return { success: true, blob, fileName: `${opts.reportId}.csv` };
}

const HANDLERS: Record<ExportFormat, (opts: ExportOptions) => Promise<ExportResult>> = {
  pdf: handlePdfExport,
  word: handleWordExport,
  html: handleHtmlExport,
  txt: handleTextExport,
  hl7: handleHl7Export,
  'dicom-sr': handleDicomSrExport,
  csv: handleCsvExport,
};

export function exportReport(options: ExportOptions): Promise<ExportResult> {
  if (!options.reportId) {
    return Promise.resolve({ success: false, error: 'reportId is required' });
  }
  const handler = HANDLERS[options.format];
  if (!handler) {
    return Promise.resolve({ success: false, error: `Unsupported format: ${options.format}` });
  }
  return handler(options);
}

export async function exportToPdf(reportId: string, options?: Partial<ExportOptions>): Promise<ExportResult> {
  return exportReport({ format: 'pdf', reportId, ...options });
}

export async function exportToWord(reportId: string): Promise<ExportResult> {
  return exportReport({ format: 'word', reportId });
}

export async function exportToHtml(reportId: string): Promise<ExportResult> {
  return exportReport({ format: 'html', reportId });
}

export async function exportToText(reportId: string): Promise<ExportResult> {
  return exportReport({ format: 'txt', reportId });
}

export async function exportToEncryptedPdf(
  reportId: string,
  patientName: string,
  findings: string,
  impression: string,
  password: string,
): Promise<ExportResult> {
  return getEncryptedPdfExporter().exportEncrypted(
    reportId,
    { title: '放射诊断报告', patientName, findings, impression },
    { userPassword: password },
  );
}

export async function exportToPptx(
  title: string,
  slides: { title: string; body: string }[],
  author?: string,
): Promise<ExportResult> {
  return getPptxExporter().export({
    title,
    author,
    slides: slides.map(s => ({ title: s.title, body: s.body, layout: 'content' })),
  });
}

