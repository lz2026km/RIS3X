export function findProceduresByCategory(category: InterventionalProcedure['category']): InterventionalProcedure[] {
  return INTERVENTIONAL_PROCEDURES.filter((p) => p.category === category)
}

export function findProcedureByCode(code: string): InterventionalProcedure | undefined {
  return INTERVENTIONAL_PROCEDURES.find((p) => p.code === code)
}

export function searchProcedures(keyword: string): InterventionalProcedure[] {
  const k = keyword.trim().toLowerCase()
  if (!k) return INTERVENTIONAL_PROCEDURES
  return INTERVENTIONAL_PROCEDURES.filter(
    (p) =>
      p.name.toLowerCase().includes(k) ||
      p.englishName.toLowerCase().includes(k) ||
      p.bodyPart.includes(k) ||
      p.code.toLowerCase().includes(k),
  )
}

