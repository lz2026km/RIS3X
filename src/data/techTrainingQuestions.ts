export function getQuestionsByCategory(category: TechTrainingQuestion['category']): TechTrainingQuestion[] {
  return TECH_TRAINING_QUESTIONS.filter((q) => q.category === category)
}

export function getQuestionsByDifficulty(difficulty: 1 | 2 | 3): TechTrainingQuestion[] {
  return TECH_TRAINING_QUESTIONS.filter((q) => q.difficulty === difficulty)
}

export function generateExamPaper(count: number, categories?: TechTrainingQuestion['category'][]): TechTrainingQuestion[] {
  let pool = TECH_TRAINING_QUESTIONS
  if (categories && categories.length > 0) {
    pool = pool.filter((q) => categories.includes(q.category))
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}

export function checkAnswer(question: TechTrainingQuestion, selected: number | number[]): boolean {
  if (question.type === '多选') {
    const a = Array.isArray(question.answer) ? question.answer.sort().join(',') : String(question.answer)
    const s = Array.isArray(selected) ? selected.sort().join(',') : String(selected)
    return a === s
  }
  return question.answer === selected
}

