export function findRadByIsotope(isotope: string): Radiopharmaceutical[] {
  return RADIOPHARMACEUTICALS.filter((r) => r.isotope === isotope)
}

export function searchRadiopharmaceuticals(keyword: string): Radiopharmaceutical[] {
  const k = keyword.trim().toLowerCase()
  if (!k) return RADIOPHARMACEUTICALS
  return RADIOPHARMACEUTICALS.filter(
    (r) =>
      r.name.toLowerCase().includes(k) ||
      r.englishName.toLowerCase().includes(k) ||
      r.indication.includes(k) ||
      r.code.toLowerCase().includes(k),
  )
}

