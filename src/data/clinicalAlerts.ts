export function findAlertsByCategory(category: ClinicalAlertRule['category']): ClinicalAlertRule[] {
  return CLINICAL_ALERT_RULES.filter((r) => r.category === category)
}

export function findAlertsByModality(modality: string): ClinicalAlertRule[] {
  return CLINICAL_ALERT_RULES.filter((r) => r.modality.includes(modality))
}

export function findCriticalAlerts(): ClinicalAlertRule[] {
  return CLINICAL_ALERT_RULES.filter((r) => r.severity === 'critical')
}

export function searchAlertRules(keyword: string): ClinicalAlertRule[] {
  const k = keyword.trim().toLowerCase()
  if (!k) return CLINICAL_ALERT_RULES
  return CLINICAL_ALERT_RULES.filter(
    (r) => r.title.includes(k) || r.bodyPart.includes(k) || r.findings.some((f) => f.includes(k)),
  )
}

