/** 按模态检索核查清单（filter by modality, e.g. 'DSA' / 'CT 引导'） */
export function filterChecklistsByModality(modality: string): SurgeryChecklist[] {
  return SURGERY_CHECKLISTS.filter((c) => c.modality.includes(modality));
}

/** 按关键词检索核查清单及项目（手术名称/核查项/耗材，search by keyword） */
export function searchSurgeryChecklists(keyword: string): SurgeryChecklist[] {
  const kw = keyword.trim().toLowerCase();
  if (!kw) return SURGERY_CHECKLISTS;
  return SURGERY_CHECKLISTS.filter((c) => {
    const inMeta =
      c.procedure.toLowerCase().includes(kw) || c.modality.toLowerCase().includes(kw);
    const inChecks = c.phases.some((p) => p.checks.some((ch) => ch.toLowerCase().includes(kw)));
    const inSupplies = c.supplies.some((s) => s.toLowerCase().includes(kw));
    return inMeta || inChecks || inSupplies;
  });
}

/** 统计每类手术核查项总数（for checklist completion tracking） */
export function getChecklistItemCounts(): Array<{ procedure: string; totalChecks: number; phaseCount: number }> {
  return SURGERY_CHECKLISTS.map((c) => ({
    procedure: c.procedure,
    totalChecks: c.phases.reduce((sum, p) => sum + p.checks.length, 0),
    phaseCount: c.phases.length,
  }));
}
