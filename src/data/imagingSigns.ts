/** 按系统分类筛选征象（filter by category, e.g. '肺' / '脑'） */
export function filterImagingSignsByCategory(category: ImagingSignCategory): ImagingSign[] {
  return IMAGING_SIGNS.filter((sign) => sign.category === category);
}

/** 按关键词检索征象（中英文名称 / 描述 / 鉴别诊断，search by keyword） */
export function searchImagingSigns(keyword: string): ImagingSign[] {
  const kw = keyword.trim().toLowerCase();
  if (!kw) return IMAGING_SIGNS;
  return IMAGING_SIGNS.filter(
    (sign) =>
      sign.name.toLowerCase().includes(kw) ||
      sign.englishName.toLowerCase().includes(kw) ||
      sign.description.toLowerCase().includes(kw) ||
      sign.differential.toLowerCase().includes(kw),
  );
}

/** 获取全部征象分类（含数量统计，for category statistics） */
export function getSignCategoryStats(): Array<{ category: ImagingSignCategory; count: number }> {
  return (['肺', '纵隔', '腹', '骨', '脑', '乳腺'] as const).map((category) => ({
    category,
    count: IMAGING_SIGNS.filter((sign) => sign.category === category).length,
  }));
}
